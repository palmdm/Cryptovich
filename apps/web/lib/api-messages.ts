export function translateApiMessage(message: string, t: (key: TranslationKey) => string): string {
  const exact = API_MESSAGES[message];
  if (exact) return t(exact) || message;
  for (const { pattern, key } of API_TEMPLATES) {
    const match = message.match(pattern);
    if (!match) continue;
    const template = t(key);
    if (!template) return message;
    return template.replace(/\{(\d)\}/g, (_, i: string) => {
      const value = match[Number(i) + 1] ?? "";
      // "Post could not be found" → "Не найдено: пост".
      const noun = key === "api.t.notFound" ? API_NOUNS[value] : undefined;
      return noun ? t(noun) || value : value;
    });
  }
  return message;
}
